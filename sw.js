const CACHE_NAME = 'bonomi-v4-clean-paper';
const ASSETS = [
  './',
  './index.html',
  './favicon.ico',
  './favicon-32x32.png',
  './apple-touch-icon.png',
  './og_capa.jpg?v=2',
  './manifest.json'
];

self.addEventListener('install', event => {
  // Ativa imediatamente a nova versão sem esperar fechar abas
  self.skipWaiting();
  event.waitUntil(
    caches.open(CACHE_NAME).then(cache => cache.addAll(ASSETS))
  );
});

self.addEventListener('activate', event => {
  // Limpa 100% dos caches antigos legados
  event.waitUntil(
    caches.keys().then(keys => Promise.all(
      keys.filter(k => k !== CACHE_NAME).map(k => caches.delete(k))
    )).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;

  const isHtml = event.request.mode === 'navigate' || 
                 (event.request.headers.get('accept') && event.request.headers.get('accept').includes('text/html'));

  if (isHtml) {
    // ESTRATÉGIA NETWORK-FIRST PARA O HTML:
    // Garante que o cliente veja SEMPRE a versão mais recente e as cores oficiais em tempo real!
    event.respondWith(
      fetch(event.request)
        .then(response => {
          if (response && response.status === 200) {
            const clone = response.clone();
            caches.open(CACHE_NAME).then(cache => cache.put(event.request, clone));
          }
          return response;
        })
        .catch(() => caches.match(event.request).then(cached => cached || caches.match('./index.html')))
    );
    return;
  }

  // Para assets estáticos: Cache First com fallback para Network
  event.respondWith(
    caches.match(event.request).then(cached => {
      return cached || fetch(event.request).then(response => {
        if (response && response.status === 200 && event.request.url.startsWith('http')) {
          const clone = response.clone();
          caches.open(CACHE_NAME).then(cache => cache.put(event.request, clone));
        }
        return response;
      });
    })
  );
});
